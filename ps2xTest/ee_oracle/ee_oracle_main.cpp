// ps2x_ee_oracle: replays EE oracle vectors against the recompiled C++ (T-0002 tier T2).
//
// The vectors come from tools/ee_oracle/gen (ps2-oracle, an independent R5900 interpreter running the
// game's own code). For every case this rebuilds the inputs (ee_oracle_inputs.h), runs the recompiled
// function, and compares every GPR (128-bit), FPR, ACC, the FPU condition flag, HI/LO/HI1/LO1, VU0
// VF1-31/ACC/Q, the four input buffers and the stack window byte for byte, plus every byte the oracle
// wrote elsewhere.
//
// usage: ps2x_ee_oracle <vectors.bin> <TC2.ELF> [--func NAME] [--case N] [-v] [--ulp N] [--strict]
//                       [--examples N] [--known FILE] [--case-timeout-ms MS]
//
// Each case lands in one class:
//   exact    bit-identical
//   ulp      only 32-bit float values differ, each by <= --ulp units in the last place (default 4).
//            Known divergence: the runtime's FPU rounds to nearest, the PS2 (and ps2-float) chops.
//   mixed    a non-float difference and float differences in the same case (often a branch that went
//            the other way because of a rounding difference)
//   LOGIC    non-float differences only: a codegen/semantics bug. Exit status 1 when any occur.
// --strict makes every non-exact case fail (implied for runtime-model vectors). --known lists recorded bugs
// (function + exact failing-case count) that do not fail the run while the count is unchanged.
// A case that has not returned after --case-timeout-ms (default 2000; POSIX hosts) is stopped and counts
// as LOGIC: a runaway loop the oracle did not take.
// Vectors from `ee-oracle-gen arith` instead check every float helper op by op against the runtime model.
// The last line of output is a one-line verdict.

